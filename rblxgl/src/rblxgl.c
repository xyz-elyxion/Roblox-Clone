static int find_extensionsGL(void) {
	if (!get_exts()) return 0;
	(void)&has_ext;
	free_exts();
	return 1;
}

static void find_coreGL(void) {

    /* Thank you @elmindreda
     * https://github.com/elmindreda/greg/blob/master/templates/greg.c.in#L176
     * https://github.com/rblxwin/rblxwin/blob/master/src/context.c#L36
     */
    int i, major, minor;

    const char* version;
    const char* prefixes[] = {
        "OpenGL ES-CM ",
        "OpenGL ES-CL ",
        "OpenGL ES ",
        NULL
    };

    version = (const char*) glGetString(GL_VERSION);
    if (!version) return;

    for (i = 0;  prefixes[i];  i++) {
        const size_t length = strlen(prefixes[i]);
        if (strncmp(version, prefixes[i], length) == 0) {
            version += length;
            break;
        }
    }

/* PR #18 */
#ifdef _MSC_VER
    sscanf_s(version, "%d.%d", &major, &minor);
#else
    sscanf(version, "%d.%d", &major, &minor);
#endif

    GLVersion.major = major; GLVersion.minor = minor;
    max_loaded_major = major; max_loaded_minor = minor;
	RBLXGL_GL_VERSION_1_0 = (major == 1 && minor >= 0) || major > 1;
	RBLXGL_GL_VERSION_1_1 = (major == 1 && minor >= 1) || major > 1;
	RBLXGL_GL_VERSION_1_2 = (major == 1 && minor >= 2) || major > 1;
	RBLXGL_GL_VERSION_1_3 = (major == 1 && minor >= 3) || major > 1;
	RBLXGL_GL_VERSION_1_4 = (major == 1 && minor >= 4) || major > 1;
	RBLXGL_GL_VERSION_1_5 = (major == 1 && minor >= 5) || major > 1;
	RBLXGL_GL_VERSION_2_0 = (major == 2 && minor >= 0) || major > 2;
	RBLXGL_GL_VERSION_2_1 = (major == 2 && minor >= 1) || major > 2;
	RBLXGL_GL_VERSION_3_0 = (major == 3 && minor >= 0) || major > 3;
	RBLXGL_GL_VERSION_3_1 = (major == 3 && minor >= 1) || major > 3;
	RBLXGL_GL_VERSION_3_2 = (major == 3 && minor >= 2) || major > 3;
	RBLXGL_GL_VERSION_3_3 = (major == 3 && minor >= 3) || major > 3;
	RBLXGL_GL_VERSION_4_0 = (major == 4 && minor >= 0) || major > 4;
	RBLXGL_GL_VERSION_4_1 = (major == 4 && minor >= 1) || major > 4;
	if (GLVersion.major > 4 || (GLVersion.major >= 4 && GLVersion.minor >= 1)) {
		max_loaded_major = 4;
		max_loaded_minor = 1;
	}
}

int rblxglLoadGLLoader(RBLXGLloadproc load) {
	GLVersion.major = 0; GLVersion.minor = 0;
	glGetString = (PFNGLGETSTRINGPROC)load("glGetString");
	if(glGetString == NULL) return 0;
	if(glGetString(GL_VERSION) == NULL) return 0;
	find_coreGL();
	load_GL_VERSION_1_0(load);
	load_GL_VERSION_1_1(load);
	load_GL_VERSION_1_2(load);
	load_GL_VERSION_1_3(load);
	load_GL_VERSION_1_4(load);
	load_GL_VERSION_1_5(load);
	load_GL_VERSION_2_0(load);
	load_GL_VERSION_2_1(load);
	load_GL_VERSION_3_0(load);
	load_GL_VERSION_3_1(load);
	load_GL_VERSION_3_2(load);
	load_GL_VERSION_3_3(load);
	load_GL_VERSION_4_0(load);
	load_GL_VERSION_4_1(load);

	if (!find_extensionsGL()) return 0;
	return GLVersion.major != 0 || GLVersion.minor != 0;
}

