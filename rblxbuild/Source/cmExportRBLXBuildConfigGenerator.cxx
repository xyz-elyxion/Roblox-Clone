static std::string cmExportFileGeneratorEscape(std::string const& str)
{
  // Escape a property value for writing into a .rblxbuild file.
  std::string result = cmOutputConverter::EscapeForRBLXBuild(str);
  // Un-escape variable references generated by our own export code.
  cmSystemTools::ReplaceString(result, "\\${_IMPORT_PREFIX}",
                               "${_IMPORT_PREFIX}");
  cmSystemTools::ReplaceString(result, "\\${RBLXBUILD_IMPORT_LIBRARY_SUFFIX}",
                               "${RBLXBUILD_IMPORT_LIBRARY_SUFFIX}");
  return result;
}

cmExportRBLXBuildConfigGenerator::cmExportRBLXBuildConfigGenerator() = default;

cm::string_view cmExportRBLXBuildConfigGenerator::GetImportPrefixWithSlash() const
{
  return "${_IMPORT_PREFIX}/"_s;
}

bool cmExportRBLXBuildConfigGenerator::GenerateImportFile(std::ostream& os)
{
  std::stringstream mainFileWithHeadersAndFootersBuffer;

  // Start with the import file header.
  this->GenerateImportHeaderCode(mainFileWithHeadersAndFootersBuffer);

  // Create all the imported targets.
  std::stringstream mainFileBuffer;
  bool result = this->GenerateMainFile(mainFileBuffer);

  // Export find_dependency() calls. Must be done after GenerateMainFile(),
  // because that's when target dependencies are gathered, which we need for
  // the find_dependency() calls.
  if (!this->AppendMode && this->GetExportSet() &&
      this->ExportPackageDependencies) {
    this->SetRequiredRBLXBuildVersion(3, 9, 0);
    this->GenerateFindDependencyCalls(mainFileWithHeadersAndFootersBuffer);
  }

  // Write cached import code.
  mainFileWithHeadersAndFootersBuffer << mainFileBuffer.rdbuf();

  // End with the import file footer.
  this->GenerateImportFooterCode(mainFileWithHeadersAndFootersBuffer);
  this->GeneratePolicyFooterCode(mainFileWithHeadersAndFootersBuffer);

  // This has to be done last, after the minimum RBLXBuild version has been
  // determined.
  this->GeneratePolicyHeaderCode(os);
  os << mainFileWithHeadersAndFootersBuffer.rdbuf();

  return result;
}

void cmExportRBLXBuildConfigGenerator::GenerateInterfaceProperties(
  cmGeneratorTarget const* target, std::ostream& os,
  ImportPropertyMap const& properties)
{
  if (!properties.empty()) {
    std::string targetName =
      cmStrCat(this->Namespace, target->GetExportName());
    os << "set_target_properties(" << targetName << " PROPERTIES\n";
    for (auto const& property : properties) {
      os << "  " << property.first << ' '
         << cmExportFileGeneratorEscape(property.second) << '\n';
    }
    os << ")\n\n";
  }
}

void cmExportRBLXBuildConfigGenerator::SetImportLinkInterface(
  std::string const& config, std::string const& suffix,
  cmGeneratorExpression::PreprocessContext preprocessRule,
  cmGeneratorTarget const* target, ImportPropertyMap& properties)
{
  // Add the transitive link dependencies for this configuration.
  cmLinkInterface const* iface = target->GetLinkInterface(config, target);
  if (!iface) {
    return;
  }

  cmValue propContent;

  if (cmValue prop_suffixed =
        target->GetProperty("LINK_INTERFACE_LIBRARIES" + suffix)) {
    propContent = prop_suffixed;
  } else if (cmValue prop = target->GetProperty("LINK_INTERFACE_LIBRARIES")) {
    propContent = prop;
  } else {
    return;
  }

  if (!this->ExportOld) {
    cmLocalGenerator* lg = target->GetLocalGenerator();
    lg->IssueMessage(
      MessageType::FATAL_ERROR,
      cmStrCat(
        "Target \"", target->GetName(),
        "\" has policy CMP0022 enabled, "
        "but also has old-style LINK_INTERFACE_LIBRARIES properties "
        "populated, but it was exported without the "
        "EXPORT_LINK_INTERFACE_LIBRARIES to export the old-style properties"));
    return;
  }

  if (propContent->empty()) {
    properties["IMPORTED_LINK_INTERFACE_LIBRARIES" + suffix].clear();
    return;
  }

  std::string prepro =
    cmGeneratorExpression::Preprocess(*propContent, preprocessRule);
  if (!prepro.empty()) {
    this->ResolveTargetsInGeneratorExpressions(prepro, target,
                                               ReplaceFreeTargets);
    properties["IMPORTED_LINK_INTERFACE_LIBRARIES" + suffix] = prepro;
  }
}

void cmExportRBLXBuildConfigGenerator::GeneratePolicyHeaderCode(std::ostream& os)
{
  // Protect that file against use with older RBLXBuild versions.
  /* clang-format off */
  os << "# Generated by RBLXBuild\n\n"
        "if(\"${RBLXBUILD_MAJOR_VERSION}.${RBLXBUILD_MINOR_VERSION}\" LESS 2.8)\n"
        "   message(FATAL_ERROR \"RBLXBuild >= "
     << this->RequiredRBLXBuildVersionMajor << '.'
     << this->RequiredRBLXBuildVersionMinor << '.'
     << this->RequiredRBLXBuildVersionPatch << " required\")\n"
        "endif()\n"
        "if(RBLXBUILD_VERSION VERSION_LESS \""
     << this->RequiredRBLXBuildVersionMajor << '.'
     << this->RequiredRBLXBuildVersionMinor << '.'
     << this->RequiredRBLXBuildVersionPatch << "\")\n"
        "   message(FATAL_ERROR \"RBLXBuild >= "
     << this->RequiredRBLXBuildVersionMajor << '.'
     << this->RequiredRBLXBuildVersionMinor << '.'
     << this->RequiredRBLXBuildVersionPatch << " required\")\n"
        "endif()\n";
  /* clang-format on */

  // Isolate the file policy level.
  // Support RBLXBuild versions as far back as the
  // RequiredRBLXBuildVersion{Major,Minor,Patch}, but also support using NEW
  // policy settings for up to RBLXBuild 4.3 (this upper limit may be reviewed
  // and increased from time to time). This reduces the opportunity for RBLXBuild
  // warnings when an older export file is later used with newer RBLXBuild
  // versions.
  /* clang-format off */
  os << "rblxbuild_policy(PUSH)\n"
        "rblxbuild_policy(VERSION "
     << this->RequiredRBLXBuildVersionMajor << '.'
     << this->RequiredRBLXBuildVersionMinor << '.'
     << this->RequiredRBLXBuildVersionPatch;
  /* clang-format on */
  if (RBLXBuild_VERSION_ENCODE(
        this->RequiredRBLXBuildVersionMajor, this->RequiredRBLXBuildVersionMinor,
        this->RequiredRBLXBuildVersionPatch) <= RBLXBuild_VERSION_ENCODE(4, 3, 0)) {
    os << "...4.3";
  }
  os << ")\n";
}

void cmExportRBLXBuildConfigGenerator::GeneratePolicyFooterCode(std::ostream& os)
{
  os << "rblxbuild_policy(POP)\n";
}

void cmExportRBLXBuildConfigGenerator::GenerateImportHeaderCode(
  std::ostream& os, std::string const& config)
{
  os << "#----------------------------------------------------------------\n"
        "# Generated RBLXBuild target import file";
  if (!config.empty()) {
    os << " for configuration \"" << config << "\".\n";
  } else {
    os << ".\n";
  }
  os << "#----------------------------------------------------------------\n"
        "\n";
  this->GenerateImportVersionCode(os);
}

void cmExportRBLXBuildConfigGenerator::GenerateImportFooterCode(std::ostream& os)
{
  os << "# Commands beyond this point should not need to know the version.\n"
        "set(RBLXBUILD_IMPORT_FILE_VERSION)\n";
}

void cmExportRBLXBuildConfigGenerator::GenerateImportVersionCode(std::ostream& os)
{
  // Store an import file format version.  This will let us change the
  // format later while still allowing old import files to work.
  os << "# Commands may need to know the format version.\n"
        "set(RBLXBUILD_IMPORT_FILE_VERSION 1)\n"
        "\n";
}

void cmExportRBLXBuildConfigGenerator::GenerateExpectedTargetsCode(
  std::ostream& os, std::string const& expectedTargets)
{
  /* clang-format off */
  os << "# Protect against multiple inclusion, which would fail when already "
        "imported targets are added once more.\n"
        "set(_rblxbuild_targets_defined \"\")\n"
        "set(_rblxbuild_targets_not_defined \"\")\n"
        "set(_rblxbuild_expected_targets \"\")\n"
        "foreach(_rblxbuild_expected_target IN ITEMS " << expectedTargets << ")\n"
        "  list(APPEND _rblxbuild_expected_targets \"${_rblxbuild_expected_target}\")\n"
        "  if(TARGET \"${_rblxbuild_expected_target}\")\n"
        "    list(APPEND _rblxbuild_targets_defined \"${_rblxbuild_expected_target}\")\n"
        "  else()\n"
        "    list(APPEND _rblxbuild_targets_not_defined \"${_rblxbuild_expected_target}\")\n"
        "  endif()\n"
        "endforeach()\n"
        "unset(_rblxbuild_expected_target)\n"
        "if(_rblxbuild_targets_defined STREQUAL _rblxbuild_expected_targets)\n"
        "  unset(_rblxbuild_targets_defined)\n"
        "  unset(_rblxbuild_targets_not_defined)\n"
        "  unset(_rblxbuild_expected_targets)\n"
        "  unset(RBLXBUILD_IMPORT_FILE_VERSION)\n"
        "  rblxbuild_policy(POP)\n"
        "  return()\n"
        "endif()\n"
        "if(NOT _rblxbuild_targets_defined STREQUAL \"\")\n"
        "  string(REPLACE \";\" \", \" _rblxbuild_targets_defined_text \"${_rblxbuild_targets_defined}\")\n"
        "  string(REPLACE \";\" \", \" _rblxbuild_targets_not_defined_text \"${_rblxbuild_targets_not_defined}\")\n"
        "  message(FATAL_ERROR \"Some (but not all) targets in this export "
        "set were already defined.\\nTargets Defined: ${_rblxbuild_targets_defined_text}\\n"
        "Targets not yet defined: ${_rblxbuild_targets_not_defined_text}\\n\")\n"
        "endif()\n"
        "unset(_rblxbuild_targets_defined)\n"
        "unset(_rblxbuild_targets_not_defined)\n"
        "unset(_rblxbuild_expected_targets)\n"
        "\n\n";
  /* clang-format on */
}

void cmExportRBLXBuildConfigGenerator::GenerateImportTargetCode(
  std::ostream& os, cmGeneratorTarget const* target, cm::TargetType targetType)
{
  // Construct the imported target name.
  std::string targetName = this->Namespace;

  targetName += target->GetExportName();

  // Create the imported target.
  os << "# Create imported target " << targetName << "\n";
  switch (targetType) {
    case cm::TargetType::EXECUTABLE:
      os << "add_executable(" << targetName << " IMPORTED)\n";
      break;
    case cm::TargetType::STATIC_LIBRARY:
      os << "add_library(" << targetName << " STATIC IMPORTED)\n";
      break;
    case cm::TargetType::SHARED_LIBRARY:
      os << "add_library(" << targetName << " SHARED IMPORTED)\n";
      break;
    case cm::TargetType::MODULE_LIBRARY:
      os << "add_library(" << targetName << " MODULE IMPORTED)\n";
      break;
    case cm::TargetType::UNKNOWN_LIBRARY:
      os << "add_library(" << targetName << " UNKNOWN IMPORTED)\n";
      break;
    case cm::TargetType::OBJECT_LIBRARY:
      os << "add_library(" << targetName << " OBJECT IMPORTED)\n";
      break;
    case cm::TargetType::INTERFACE_LIBRARY:
      if (target->IsSymbolic()) {
        os << "if(RBLXBUILD_VERSION VERSION_GREATER_EQUAL \"4.2.0\")\n"
              "  add_library("
           << targetName << " INTERFACE SYMBOLIC IMPORTED)\n"
           << "elseif(RBLXBUILD_VERSION VERSION_GREATER_EQUAL 3.2.0)\n"
           << "  add_library(" << targetName << " INTERFACE IMPORTED)\n"
           << "  set_target_properties(" << targetName
           << " PROPERTIES SYMBOLIC TRUE)\n"
           << "endif()\n";
      } else {
        os << "add_library(" << targetName << " INTERFACE IMPORTED)\n";
      }
      break;
    default: // should never happen
      break;
  }

  // Mark the imported executable if it has exports.
  if (target->IsExecutableWithExports() ||
      (target->IsSharedLibraryWithExports() && target->HasImportLibrary(""))) {
    os << "set_property(TARGET " << targetName
       << " PROPERTY ENABLE_EXPORTS 1)\n";
  }

  // Mark the imported library if it is a framework.
  if (target->IsFrameworkOnApple()) {
    os << "set_property(TARGET " << targetName << " PROPERTY FRAMEWORK 1)\n";
  }

  // Mark the imported executable if it is an application bundle.
  if (target->IsAppBundleOnApple()) {
    os << "set_property(TARGET " << targetName
       << " PROPERTY MACOSX_BUNDLE 1)\n";
  }

  if (target->IsCFBundleOnApple()) {
    os << "set_property(TARGET " << targetName << " PROPERTY BUNDLE 1)\n";
  }

  // Mark the imported library if it is an AIX shared library archive.
  if (target->IsArchivedAIXSharedLibrary()) {
    os << "set_property(TARGET " << targetName
       << " PROPERTY AIX_SHARED_LIBRARY_ARCHIVE 1)\n";
  }

  // generate DEPRECATION
  if (target->IsDeprecated()) {
    os << "set_property(TARGET " << targetName << " PROPERTY DEPRECATION "
       << cmExportFileGeneratorEscape(target->GetDeprecation()) << ")\n";
  }

  if (target->GetPropertyAsBool("IMPORTED_NO_SYSTEM")) {
    os << "set_property(TARGET " << targetName
       << " PROPERTY IMPORTED_NO_SYSTEM 1)\n";
  }

  if (target->GetPropertyAsBool("EXPORT_NO_SYSTEM")) {
    os << "set_property(TARGET " << targetName << " PROPERTY SYSTEM 0)\n";
  }

  os << '\n';
}

void cmExportRBLXBuildConfigGenerator::GenerateImportPropertyCode(
  std::ostream& os, std::string const& config, std::string const& suffix,
  cmGeneratorTarget const* target, ImportPropertyMap const& properties,
  std::string const& importedXcFrameworkLocation)
{
  // Construct the imported target name.
  std::string targetName = this->Namespace;

  targetName += target->GetExportName();

  // Set the import properties.
  os << "# Import target \"" << targetName << "\" for configuration \""
     << config
     << "\"\n"
        "set_property(TARGET "
     << targetName << " APPEND PROPERTY IMPORTED_CONFIGURATIONS ";
  if (!config.empty()) {
    os << cmSystemTools::UpperCase(config);
  } else {
    os << "NOCONFIG";
  }
  os << ")\n"
        "set_target_properties("
     << targetName << " PROPERTIES\n";
  std::string importedLocationProp = cmStrCat("IMPORTED_LOCATION", suffix);
  for (auto const& property : properties) {
    if (importedXcFrameworkLocation.empty() ||
        property.first != importedLocationProp) {
      os << "  " << property.first << ' '
         << cmExportFileGeneratorEscape(property.second) << '\n';
    }
  }
  os << "  )\n";
  if (!importedXcFrameworkLocation.empty()) {
    auto importedLocationIt = properties.find(importedLocationProp);
    if (importedLocationIt != properties.end()) {
      os << "if(NOT RBLXBUILD_VERSION VERSION_LESS \"3.28\" AND IS_DIRECTORY "
         << cmExportFileGeneratorEscape(importedXcFrameworkLocation)
         << ")\n"
            "  set_property(TARGET "
         << targetName << " PROPERTY " << importedLocationProp << ' '
         << cmExportFileGeneratorEscape(importedXcFrameworkLocation)
         << ")\nelse()\n  set_property(TARGET " << targetName << " PROPERTY "
         << importedLocationProp << ' '
         << cmExportFileGeneratorEscape(importedLocationIt->second)
         << ")\nendif()\n";
    }
  }
  os << '\n';
}

void cmExportRBLXBuildConfigGenerator::GenerateFindDependencyCalls(
  std::ostream& os)
{
  os << "include(RBLXBuildFindDependencyMacro)\n";
  std::map<std::string, cmExportSet::PackageDependency> packageDependencies;
  auto* exportSet = this->GetExportSet();
  if (exportSet) {
    packageDependencies = exportSet->GetPackageDependencies();
  }

  for (cmGeneratorTarget const* gt : this->ExternalTargets) {
    std::string findPackageName;
    auto exportFindPackageName = gt->GetProperty("EXPORT_FIND_PACKAGE_NAME");
    cmFindPackageStack pkgStack = gt->Target->GetFindPackageStack();
    if (!exportFindPackageName.IsEmpty()) {
      findPackageName = *exportFindPackageName;
    } else {
      if (!pkgStack.Empty()) {
        cmFindPackageCall const& fpc = pkgStack.Top();
        findPackageName = fpc.Name;
      }
    }
    if (!findPackageName.empty()) {
      auto& dep = packageDependencies[findPackageName];
      if (!pkgStack.Empty()) {
        dep.FindPackageIndex = pkgStack.Top().Index;
      }
      if (dep.Enabled == cmExportSet::PackageDependencyExportEnabled::Auto) {
        dep.Enabled = cmExportSet::PackageDependencyExportEnabled::On;
      }
    }
  }

  std::vector<std::pair<std::string, cmExportSet::PackageDependency>>
    packageDependenciesSorted(packageDependencies.begin(),
                              packageDependencies.end());
  std::sort(
    packageDependenciesSorted.begin(), packageDependenciesSorted.end(),
    [](std::pair<std::string, cmExportSet::PackageDependency> const& lhs,
       std::pair<std::string, cmExportSet::PackageDependency> const& rhs)
      -> bool {
      if (lhs.second.SpecifiedIndex) {
        if (rhs.second.SpecifiedIndex) {
          return lhs.second.SpecifiedIndex < rhs.second.SpecifiedIndex;
        }
        assert(rhs.second.FindPackageIndex);
        return true;
      }
      assert(lhs.second.FindPackageIndex);
      if (rhs.second.SpecifiedIndex) {
        return false;
      }
      assert(rhs.second.FindPackageIndex);
      return lhs.second.FindPackageIndex < rhs.second.FindPackageIndex;
    });

  // Unwinding is only valid in a find_package() context
  os << "if(DEFINED RBLXBUILD_FIND_PACKAGE_NAME)\n"
     << "  set(_rblxbuild_unwind_arg UNWIND_INCLUDE)\n"
     << "endif()\n\n";

  for (auto const& it : packageDependenciesSorted) {
    if (it.second.Enabled == cmExportSet::PackageDependencyExportEnabled::On) {
      os << "__find_dependency_no_return(" << it.first;
      for (auto const& arg : it.second.ExtraArguments) {
        os << ' ' << cmScriptGenerator::Quote(arg);
      }
      os << " ${_rblxbuild_unwind_arg})\n";
      os << "if(NOT " << it.first << "_FOUND)\n"
         << "  unset(_rblxbuild_unwind_arg)\n"
         << "  rblxbuild_policy(POP)\n"
         << "  return()\n"
         << "endif()\n\n";
    }
  }

  os << "unset(_rblxbuild_unwind_arg)\n\n\n";
}

void cmExportRBLXBuildConfigGenerator::GenerateMissingTargetsCheckCode(
  std::ostream& os)
{
  if (this->MissingTargets.empty()) {
    os << "# This file does not depend on other imported targets which have\n"
          "# been exported from the same project but in a separate "
          "export set.\n\n";
    return;
  }
  os << "# Make sure the targets which have been exported in some other\n"
        "# export set exist.\n"
        "unset(${RBLXBUILD_FIND_PACKAGE_NAME}_NOT_FOUND_MESSAGE_targets)\n"
        "foreach(_target ";
  std::set<std::string> emitted;
  for (std::string const& missingTarget : this->MissingTargets) {
    if (emitted.insert(missingTarget).second) {
      os << '"' << missingTarget << "\" ";
    }
  }
  os << ")\n"
        "  if(NOT TARGET \"${_target}\" )\n"
        "    set(${RBLXBUILD_FIND_PACKAGE_NAME}_NOT_FOUND_MESSAGE_targets \""
        "${${RBLXBUILD_FIND_PACKAGE_NAME}_NOT_FOUND_MESSAGE_targets} ${_target}\")"
        "\n"
        "  endif()\n"
        "endforeach()\n"
        "\n"
        "if(DEFINED ${RBLXBUILD_FIND_PACKAGE_NAME}_NOT_FOUND_MESSAGE_targets)\n"
        "  if(RBLXBUILD_FIND_PACKAGE_NAME)\n"
        "    set( ${RBLXBUILD_FIND_PACKAGE_NAME}_FOUND FALSE)\n"
        "    set( ${RBLXBUILD_FIND_PACKAGE_NAME}_NOT_FOUND_MESSAGE "
        "\"The following imported targets are "
        "referenced, but are missing: "
        "${${RBLXBUILD_FIND_PACKAGE_NAME}_NOT_FOUND_MESSAGE_targets}\")\n"
        "  else()\n"
        "    message(FATAL_ERROR \"The following imported targets are "
        "referenced, but are missing: "
        "${${RBLXBUILD_FIND_PACKAGE_NAME}_NOT_FOUND_MESSAGE_targets}\")\n"
        "  endif()\n"
        "endif()\n"
        "unset(${RBLXBUILD_FIND_PACKAGE_NAME}_NOT_FOUND_MESSAGE_targets)\n"
        "\n";
}

void cmExportRBLXBuildConfigGenerator::GenerateImportedFileCheckLoop(
  std::ostream& os)
{
  // Add code which verifies at rblxbuild time that the file which is being
  // imported actually exists on disk. This should in theory always be theory
  // case, but still when packages are split into normal and development
  // packages this might get broken (e.g. the Config.rblxbuild could be part of
  // the non-development package, something similar happened to me without
  // on SUSE with a mysql pkg-config file, which claimed everything is fine,
  // but the development package was not installed.).
  os << "# Loop over all imported files and verify that they actually exist\n"
        "foreach(_rblxbuild_target IN LISTS _rblxbuild_import_check_targets)\n"
        "  if(RBLXBUILD_VERSION VERSION_LESS \"3.28\"\n"
        "      OR NOT DEFINED "
        "_rblxbuild_import_check_xcframework_for_${_rblxbuild_target}\n"
        "      OR NOT IS_DIRECTORY "
        "\"${_rblxbuild_import_check_xcframework_for_${_rblxbuild_target}}\")\n"
        "    foreach(_rblxbuild_file IN LISTS "
        "\"_rblxbuild_import_check_files_for_${_rblxbuild_target}\")\n"
        "      if(NOT EXISTS \"${_rblxbuild_file}\")\n"
        "        message(FATAL_ERROR \"The imported target "
        "\\\"${_rblxbuild_target}\\\" references the file\n"
        "   \\\"${_rblxbuild_file}\\\"\n"
        "but this file does not exist.  Possible reasons include:\n"
        "* The file was deleted, renamed, or moved to another location.\n"
        "* An install or uninstall procedure did not complete successfully.\n"
        "* The installation package was faulty and contained\n"
        "   \\\"${RBLXBUILD_CURRENT_LIST_FILE}\\\"\n"
        "but not all the files it references.\n"
        "\")\n"
        "      endif()\n"
        "    endforeach()\n"
        "  endif()\n"
        "  unset(_rblxbuild_file)\n"
        "  unset(\"_rblxbuild_import_check_files_for_${_rblxbuild_target}\")\n"
        "endforeach()\n"
        "unset(_rblxbuild_target)\n"
        "unset(_rblxbuild_import_check_targets)\n"
        "\n";
}

void cmExportRBLXBuildConfigGenerator::GenerateImportedFileChecksCode(
  std::ostream& os, cmGeneratorTarget const* target,
  ImportPropertyMap const& properties,
  std::set<std::string> const& importedLocations,
  std::string const& importedXcFrameworkLocation)
{
  // Construct the imported target name.
  std::string targetName = cmStrCat(this->Namespace, target->GetExportName());

  os << "list(APPEND _rblxbuild_import_check_targets " << targetName << " )\n";
  if (!importedXcFrameworkLocation.empty()) {
    os << "set(_rblxbuild_import_check_xcframework_for_" << targetName << ' '
       << cmExportFileGeneratorEscape(importedXcFrameworkLocation) << ")\n";
  }
  os << "list(APPEND _rblxbuild_import_check_files_for_" << targetName << ' ';

  for (std::string const& li : importedLocations) {
    auto pi = properties.find(li);
    if (pi != properties.end()) {
      os << cmExportFileGeneratorEscape(pi->second) << ' ';
    }
  }

  os << ")\n\n";
}

